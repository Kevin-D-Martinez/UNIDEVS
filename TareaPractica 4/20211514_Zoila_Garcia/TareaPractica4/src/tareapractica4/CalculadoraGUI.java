    private void sumarValores() {
        Calculadora calc = new Calculadora();
        double respuesta = calc.sumar(Double.parseDouble(txtValor1.getText()), Double.parseDouble(txtValor2.getText()));
        txtRespuesta.setText(respuesta + "");
    }

    private void restarValores() {
        Calculadora calc = new Calculadora();
        double respuesta = calc.restar(Double.parseDouble(txtValor1.getText()), Double.parseDouble(txtValor2.getText()));
        txtRespuesta.setText(respuesta + "");
    }

    private void multiplicarValores() {
        Calculadora calc = new Calculadora();
        double respuesta = calc.multiplicar(Double.parseDouble(txtValor1.getText()), Double.parseDouble(txtValor2.getText()));
        txtRespuesta.setText(respuesta + "");
    }

    private void dividirValores() {
        Calculadora calc = new Calculadora();
        double respuesta = calc.dividir(Double.parseDouble(txtValor1.getText()), Double.parseDouble(txtValor2.getText()));
        if (respuesta == 0) {
            JOptionPane.showMessageDialog(null, "No puede dejar dividir con 0.");
        }
        txtRespuesta.setText(respuesta + "");
    }

    private void exponenciarValores() {
        Calculadora calc = new Calculadora();
        double respuesta = calc.exponenciar(Double.parseDouble(txtValor1.getText()), Double.parseDouble(txtValor2.getText()));
        txtRespuesta.setText(respuesta + "");
    }

    private void calcularRaiz() {
        Calculadora calc = new Calculadora();
        double respuesta = calc.raizCuadrada(Double.parseDouble(txtValor1.getText()));
        txtRespuesta.setText(respuesta + "");
    }

