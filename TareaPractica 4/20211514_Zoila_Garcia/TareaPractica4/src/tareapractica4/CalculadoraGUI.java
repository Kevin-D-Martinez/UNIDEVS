    private void btnConvertirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConvertirActionPerformed
        if ((txtCelsius.getText().trim().length() <= 0) && (txtFarenheit.getText().trim().length() <= 0)) {
            JOptionPane.showMessageDialog(null, "Debe llenar 1 de los campos.");
        } else if ((txtCelsius.getText().trim().length() > 0) && (txtFarenheit.getText().trim().length() > 0)) {
            JOptionPane.showMessageDialog(null, "Solo puede llenar 1 de los campos.");
        } else {
            if ((txtCelsius.getText().trim().length() > 0)) {
                Calculadora conv = new Calculadora();
                double respuesta = conv.convertirFarenheit(Double.parseDouble(txtCelsius.getText()));
                txtFarenheit.setText(respuesta + "");
            }
            else if ((txtFarenheit.getText().trim().length() > 0)) {
                Calculadora conv = new Calculadora();
                double respuesta = conv.convertirCelsius(Double.parseDouble(txtFarenheit.getText()));
                txtCelsius.setText(respuesta + "");
            }
        }
    }//GEN-LAST:event_btnConvertirActionPerformed

