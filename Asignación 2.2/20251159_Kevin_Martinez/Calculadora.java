public class Calculadora{

    //Suma dos valores que recibe por parametro y devuelve el resultado
    public int sumar(int a, int b) {
        return a + b;
    }
    
    //Suma tres valores que recibe por parametro y devuelve el resultado
    public int sumar(int a, int b, int c) {
        return a + b + c;
    }
    
    //Suma cuatro valores que recibe por parametro y devuelve el resultado
    public int sumar(int a, int b, int c, int d) {
        return a + b + c + d;
    }
    
    //Resta dos valores que recibe por parametro y devuelve el resultado
    public int restar(int a, int b) {
        return a - b;
    }
    
    //Resta tres valores que recibe por parametro y devuelve el resultado
    public int restar(int a, int b, int c) {
        return a - b - c;
    }
    
    //Resta cuatro valores que recibe por parametro y devuelve el resultado
    public int restar(int a, int b, int c, int d) {
        return a - b - c - d;
    }
    
    //Multiplica dos valores que recibe por parametro y devuelve el resultado
    public int multiplicar(int a, int b) {
        return a * b;
    }
    
    //Multiplica tres valores que recibe por parametro y devuelve el resultado
    public int multiplicar(int a, int b, int c) {
        return a * b * c;
    }
    
    //Multiplica cuatro valores que recibe por parametro y devuelve el resultado
    public int multiplicar(int a, int b, int c, int d) {
        return a * b * c * d;
    }

    //Divide dos valores que recibe por parametro y devuelve el resultado
    public int dividir(int a, int b) {
        return a / b;
    }
}