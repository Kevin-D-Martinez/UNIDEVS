     /**
     * Acción del botón "Calcular Resultado".
     * <p>
     * Lee los valores de los campos, valida rangos, calcula nota final
     * y actualiza el label con el resultado y color correspondiente.
     * </p>
     * 
     * @param evt Evento de acción generado por el botón
     */
    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        try {
            // Obtener los datos de los campos de texto
            String nombre = txtNombre.getText();
            String matricula = txtMatricula.getText();
            String carrera = txtCarrera.getText();

            // Validar que los campos de texto no estén vacíos
            if (nombre.isEmpty() || matricula.isEmpty() || carrera.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(this, "Por favor, complete los datos personales.");
                return;
            }

            // Convertir las notas a números
            double practicas = Double.parseDouble(txtPracticas.getText());
            double parciales = Double.parseDouble(txtParciales.getText());
            double asignaciones = Double.parseDouble(txtAsignaciones.getText());
            double examen = Double.parseDouble(txtExamen.getText());

            // Validar los rangos máximos
            if (practicas < 0 || practicas > 40
                    || parciales < 0 || parciales > 20
                    || asignaciones < 0 || asignaciones > 20
                    || examen < 0 || examen > 20) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error: Una de las notas excede el valor máximo permitido.");
                return;
            }

            // Crear el objeto Estudiante (POO)
            Estudiante est = new Estudiante(nombre, matricula, carrera, practicas, parciales, asignaciones, examen);

            // Calcular nota final y limitar decimales a 2
            double notaFinal = est.calcularNotaFinal();
            notaFinal = Math.round(notaFinal * 100.0) / 100.0; // Limita a 2 decimales
            String estado = est.getResultado();

            // Mostrar el resultado en lblResultado
            lblResultado.setText("Nota Final: " + notaFinal + " - " + estado);

            if (estado.equals("APROBADO")) {
                lblResultado.setForeground(java.awt.Color.GREEN);
            } else {
                lblResultado.setForeground(java.awt.Color.RED);
            }

        } catch (NumberFormatException e) {
            // Si el usuario mete letras en lugar de números
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Ingrese valores numéricos válidos en las calificaciones.");
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

