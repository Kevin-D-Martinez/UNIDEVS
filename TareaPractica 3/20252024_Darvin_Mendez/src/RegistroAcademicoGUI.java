     /**
     * Aplica un KeyListener para bloquear letras en los campos de calificaciones.
     * Permite solo números y el punto decimal.
     */
    private void agregarBloqueoLetras() {
        java.awt.event.KeyAdapter soloNumeros = new java.awt.event.KeyAdapter() {
            @Override
            public void keyTyped(java.awt.event.KeyEvent evt) {
                char c = evt.getKeyChar();
                if (!Character.isDigit(c) && c != '.') {
                    evt.consume(); // Ignora cualquier letra o símbolo no permitido
                }
            }
        };

        txtPracticas.addKeyListener(soloNumeros);
        txtParciales.addKeyListener(soloNumeros);
        txtAsignaciones.addKeyListener(soloNumeros);
        txtExamen.addKeyListener(soloNumeros);
    }

