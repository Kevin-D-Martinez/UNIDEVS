    private void txtNotaPracticasFocusLost(java.awt.event.FocusEvent evt) {//GEN-FIRST:event_txtNotaPracticasFocusLost
        if (txtNotaPracticas.getText().trim().length() != 0) {
            int nota = Integer.parseInt(txtNotaPracticas.getText());

            if (nota < 0 || nota > 30) {
                JOptionPane.showMessageDialog(null, "La nota práctica debe ser entre 0 y 30.");
                txtNotaPracticas.setText("");
            }
        }
    }//GEN-LAST:event_txtNotaPracticasFocusLost

