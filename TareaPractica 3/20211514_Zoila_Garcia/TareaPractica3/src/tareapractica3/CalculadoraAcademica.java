    private void limpiarCampos() {
        JTextField[] campos = {txtNombre, txtMatricula, txtCarrera, txtNotaPracticas, txtNotaParciales, txtNotaAsignaciones, txtNotaExamen};

        for (JTextField campo : campos) {
            campo.setText("");
        }

        lbEstado.setText("--");
        lbEstado.setForeground(Color.black);
        lbNotaTotal.setText("--");

        txtNombre.requestFocus();
    }

    private boolean validarCampos() {
        JTextField[] campos = {txtNombre, txtMatricula, txtCarrera, txtNotaPracticas, txtNotaParciales, txtNotaAsignaciones, txtNotaExamen};

        for (JTextField campo : campos) {
            if (campo.getText().trim().length() <= 0) {
                JOptionPane.showMessageDialog(null, "No puede dejar ningún campo vacío.");
                txtNombre.requestFocus();
                return false;
            }
        }

        return true;
    }

