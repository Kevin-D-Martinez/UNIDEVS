    private void btnResultadoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnResultadoActionPerformed
        if (validarCampos() == true) {
            int practicas = Integer.parseInt(txtNotaPracticas.getText());
            int parciales = Integer.parseInt(txtNotaParciales.getText());
            int asignaciones = Integer.parseInt(txtNotaAsignaciones.getText());
            int examen = Integer.parseInt(txtNotaExamen.getText());

            int notaTotal = practicas + parciales + asignaciones + examen;
            lbNotaTotal.setText(notaTotal + "");

            if (notaTotal < 61) {
                lbEstado.setForeground(Color.red);
                lbEstado.setText("Reprobado.");
            } else {
                lbEstado.setForeground(Color.BLUE);
                lbEstado.setText("Aprobado.");
            }
        }
    }//GEN-LAST:event_btnResultadoActionPerformed

